#!/usr/bin/env python3
"""Build music/ education/ design/ pages from content.json (the single source for sub-page copy).

Edit copy in editor.html, export the JSON, save it over content.json, then run:
    python3 _build_subpages.py
Also writes content.js so editor.html opens with the current copy.
"""
import html, json, os, re

ROOT = os.path.dirname(os.path.abspath(__file__))
E = lambda s: html.escape(s, quote=True)


def rich(s):
    """Escape body text but keep <em> (and turn <i> into <em>)."""
    s = re.sub(r"<(/?)i>", r"<\1em>", s)
    parts = re.split(r"(</?em>)", s)
    return "".join(p if p in ("<em>", "</em>") else html.escape(html.unescape(p), quote=False) for p in parts)


content = json.load(open(os.path.join(ROOT, "content.json")))
pages = content["pages"]
names = list(pages)

for slug, d in pages.items():
    crumbs = " ".join(
        '<a href="../%s/"%s>%s</a>' % (s, ' aria-current="page"' if s == slug else "", s) for s in names)
    items = []
    for it in d["items"]:
        link = it.get("link") or {}
        a = f'\n      <a class="go" href="{E(link["href"])}">{E(link["label"])}</a>' if link.get("href") else ""
        items.append(f'''  <li class="item">
    <img src="../assets/thumbs/{E(it["thumb"])}" alt="{E(it.get("alt", ""))}" width="128" height="128" loading="lazy">
    <div class="body">
      <div class="head"><h2>{E(it["title"])}</h2><div class="meta">{E(it["role"])}</div></div>
      <p>{rich(it["body"])}</p>{a}
    </div>
  </li>''')
    out = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{E(d["title"])}</title>
<meta name="description" content="{E(d["description"])}">
<link rel="canonical" href="https://rodikirk.com/{slug}/">
<meta name="theme-color" content="#1a1916">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,400;1,6..72,400&family=IBM+Plex+Mono:wght@400&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../sub.css?v=3">
<link rel="icon" href="../favicon.svg" type="image/svg+xml">
<link rel="icon" href="../favicon-32.png" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="../apple-touch-icon.png">
</head>
<body>
<main>
<nav class="crumbs" aria-label="sections"><a class="home" href="../">rodi kirk</a> {crumbs}</nav>
<h1>{E(slug)}</h1>
<p class="lede">{rich(d["lede"])}</p>
<ul class="work">
{chr(10).join(items)}
</ul>
<footer><a href="mailto:rodi@melodics.com">email</a><a href="../">home</a></footer>
</main>
<script>if(location.protocol==="file:")for(const a of document.querySelectorAll('a[href$="/"]'))a.href=a.getAttribute("href")+"index.html";</script>
</body>
</html>
'''
    os.makedirs(os.path.join(ROOT, slug), exist_ok=True)
    open(os.path.join(ROOT, slug, "index.html"), "w").write(out)
    print(f"{slug}/index.html  {len(d['items'])} items")

with open(os.path.join(ROOT, "content.js"), "w") as f:
    f.write("// Generated by _build_subpages.py from content.json. Read by editor.html.\n")
    f.write("window.SITE_CONTENT = " + json.dumps(content, indent=2, ensure_ascii=False) + ";\n")
print("content.js")
